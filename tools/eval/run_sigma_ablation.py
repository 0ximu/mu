#!/usr/bin/env python3
"""Run MU-Sigma pairwise ablation (baseline text vs graph-context text)."""

from __future__ import annotations

import argparse
import json
import subprocess
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def git_commit_short(cwd: Path) -> str:
    try:
        out = subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=str(cwd),
            text=True,
        )
        return out.strip()
    except Exception:
        return "unknown"


def render_report(result: dict[str, Any], name: str) -> str:
    baseline = result.get("baseline", {})
    graph_ctx = result.get("graph_context", {})
    by_type = result.get("by_pair_type", {})

    lines: list[str] = []
    lines.append(f"# Sigma Ablation Report: {name}")
    lines.append("")
    lines.append(f"- Pair count: {result.get('pair_count', 0)}")
    lines.append(f"- Unique texts: {result.get('unique_text_count', 0)}")
    lines.append("")
    lines.append("| Variant | Accuracy | Mean Margin |")
    lines.append("|---|---:|---:|")
    lines.append(
        f"| baseline | {baseline.get('baseline_accuracy', 0.0):.4f} | {baseline.get('baseline_mean_margin', 0.0):.4f} |"
    )
    lines.append(
        f"| graph_context | {graph_ctx.get('graph_accuracy', 0.0):.4f} | {graph_ctx.get('graph_mean_margin', 0.0):.4f} |"
    )
    lines.append(
        f"| delta (graph - baseline) | {graph_ctx.get('accuracy_delta', 0.0):+.4f} | {graph_ctx.get('mean_margin_delta', 0.0):+.4f} |"
    )
    lines.append("")

    lines.append("## Pair-Type Breakdown")
    lines.append("")
    lines.append("| Pair Type | Count | Baseline Acc | Graph Acc | Delta |")
    lines.append("|---|---:|---:|---:|---:|")

    for pair_type, stats in sorted(by_type.items()):
        lines.append(
            "| {pair_type} | {count} | {b:.4f} | {g:.4f} | {d:+.4f} |".format(
                pair_type=pair_type,
                count=stats.get("total", 0),
                b=stats.get("baseline_accuracy", 0.0),
                g=stats.get("graph_accuracy", 0.0),
                d=stats.get("accuracy_delta", 0.0),
            )
        )

    return "\n".join(lines)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run sigma graph-context ablation")
    parser.add_argument(
        "--pairs-file",
        default="data/sigma/training/training_pairs.graph.v1.json",
        help="Graph-context pairs JSON generated by generate_graph_context_pairs.py",
    )
    parser.add_argument("--batch-size", type=int, default=64)
    parser.add_argument("--name", default="sigma_ablation_phase2_3")
    parser.add_argument("--results-root", default="data/eval/results")
    parser.add_argument(
        "--cargo-cmd",
        default="cargo",
        help="Cargo executable (default: cargo)",
    )
    parser.add_argument(
        "--run-dir",
        default=".",
        help="Repo root where cargo command should run",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    cwd = Path(args.run_dir).resolve()
    pairs_file = Path(args.pairs_file).resolve()
    if not pairs_file.exists():
        raise SystemExit(f"Pairs file not found: {pairs_file}")

    commit = git_commit_short(cwd)
    out_root = Path(args.results_root).resolve() / commit
    out_root.mkdir(parents=True, exist_ok=True)
    out_json = out_root / f"{args.name}.json"
    out_md = out_root / f"{args.name}.md"

    cmd = [
        args.cargo_cmd,
        "run",
        "-p",
        "mu-embeddings",
        "--example",
        "pair_ablation",
        "--",
        "--pairs-file",
        str(pairs_file),
        "--out",
        str(out_json),
        "--batch-size",
        str(args.batch_size),
    ]
    subprocess.run(cmd, cwd=str(cwd), check=True)

    result = json.loads(out_json.read_text())
    envelope = {
        "schema_version": "sigma_ablation_run_v1",
        "generated_at": now_iso(),
        "git_commit": commit,
        "name": args.name,
        "pairs_file": str(pairs_file),
        "result": result,
    }
    out_json.write_text(json.dumps(envelope, indent=2) + "\n")
    out_md.write_text(render_report(result, args.name) + "\n")

    print(f"Wrote ablation JSON: {out_json}")
    print(f"Wrote ablation report: {out_md}")
    print(
        "Accuracy delta (graph-baseline): "
        f"{result.get('graph_context', {}).get('accuracy_delta', 0.0):+.4f}"
    )


if __name__ == "__main__":
    main()

